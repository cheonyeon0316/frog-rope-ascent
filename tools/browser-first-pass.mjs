import { chromium } from '@playwright/test';
import { launchOptions, gameURL } from './browser-config.mjs';
import { mkdir, writeFile } from 'node:fs/promises';
const output = new URL('../playtest/', import.meta.url);
await mkdir(output, { recursive: true });
const browser = await chromium.launch(launchOptions);
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
const errors = [];
const failedResponses = [];
page.on('response', r => { if(r.status() >= 400) failedResponses.push({status:r.status(),url:r.url()}); });
page.on('pageerror', e => errors.push(String(e)));
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto(gameURL);
await page.locator('#boot').waitFor({ state: 'detached', timeout: 30000 });
await page.waitForTimeout(700);
await page.screenshot({ path: new URL('title.png', output).pathname.replace(/^\/(\w:)/, '$1') });
await page.locator('#training').click();
await page.waitForTimeout(800);
await page.screenshot({ path: new URL('training-start.png', output).pathname.replace(/^\/(\w:)/, '$1') });
const result = { errors, failedResponses, title: await page.title(), state: await page.locator('#ui').getAttribute('data-state'), mode: await page.locator('#ui').getAttribute('data-mode'), height: await page.locator('#height').innerText() };
await writeFile(new URL('first-pass.json', output), JSON.stringify(result, null, 2));
console.log(JSON.stringify(result));
await browser.close();
if (errors.length) process.exitCode = 1;
