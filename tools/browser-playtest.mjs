import { chromium } from '@playwright/test';
import { launchOptions, gameURL } from './browser-config.mjs';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const output=new URL('../playtest/',import.meta.url);await mkdir(output,{recursive:true});
const browser=await chromium.launch(launchOptions);
const page=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(String(e)));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
const shots=[];
const shot=async name=>{await page.screenshot({path:fileURLToPath(new URL(name+'.png',output))});shots.push(name);};
const get=async()=>({state:await page.locator('#ui').getAttribute('data-state'),height:Number(await page.locator('#ui').getAttribute('data-height')),attached:await page.locator('#ui').getAttribute('data-attached'),peak:await page.locator('#peak').innerText(),mode:await page.locator('#ui').getAttribute('data-mode')});
const results=[];
try {
 await page.goto(gameURL);await page.locator('#boot').waitFor({state:'detached',timeout:30000});
 await page.locator('#training').click();await page.waitForTimeout(900);
 await page.mouse.move(815,155);await page.waitForTimeout(150);
 assert.match(await page.locator('#reticle').getAttribute('class'),/valid/);
 await page.mouse.down();await page.waitForTimeout(200);
 const catchState=await get();assert.equal(catchState.attached,'fly-0');results.push({action:'real-mouse-catch',...catchState});
 await page.keyboard.down('a');await page.waitForTimeout(1600);await page.keyboard.up('a');
 const swing=await get();assert.ok(Number.parseFloat(swing.peak)>0.5);results.push({action:'real-keyboard-swing',...swing});await shot('swing');
 await page.keyboard.press('Escape');await page.mouse.up();await page.waitForTimeout(200);
 const paused=await get();assert.equal(paused.state,'paused');await page.waitForTimeout(500);
 const still=await get();assert.equal(still.height,paused.height);assert.equal(still.attached,paused.attached);
 results.push({action:'pause-freezes-rope-and-position',...still});await shot('paused');
 await page.locator('#resume').click();await page.waitForTimeout(350);
 assert.equal((await get()).height,paused.height);
 await page.mouse.move(730,420);await page.mouse.down();await page.waitForTimeout(150);await page.mouse.up();await page.waitForTimeout(450);
 const released=await get();assert.equal(released.attached,'');results.push({action:'resume-reacquire-and-release',...released});await shot('flight');
 await page.keyboard.press('Escape');await page.locator('#exit').click();await page.waitForTimeout(300);
 await page.locator('#start').click();await page.waitForTimeout(700);await shot('main-start');
 await page.keyboard.down('d');await page.waitForTimeout(500);await page.keyboard.up('d');
 await page.keyboard.press('Escape');await page.waitForTimeout(250);
 const beforeSave=await get();await page.locator('#exit').click();await page.waitForTimeout(300);await page.reload();
 await page.locator('#boot').waitFor({state:'detached',timeout:30000});await page.locator('#continue').click();await page.waitForTimeout(250);
 const restored=await get();assert.equal(restored.state,'paused');assert.equal(restored.mode,'main');assert.ok(Math.abs(restored.height-beforeSave.height)<.05);
 results.push({action:'actual-browser-storage-reload',...restored});await shot('restored');
 await page.locator('#settings-pause').click();await page.locator('#setting-toggle').selectOption('true');await page.locator('#setting-quality').selectOption('low');
 await shot('settings');await page.locator('#settings-close').click();await page.locator('#resume').click();await page.waitForTimeout(350);
 await page.setViewportSize({width:1024,height:720});await page.waitForTimeout(300);await shot('small-window');
 results.push({action:'settings-and-small-window',...await get()});assert.equal(errors.length,0);
} catch(error) { results.push({failed:String(error)});await shot('failure');process.exitCode=1; }
await writeFile(new URL('browser-playtest.json',output),JSON.stringify({results,errors,screenshots:shots},null,2));
console.log(JSON.stringify({results,errors,screenshots:shots}));await browser.close();
